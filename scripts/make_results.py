"""`make results`: assemble results/RESULTS.md (EV-6) from the four result sets.

Inputs (all produced by other make targets):
  results/coverage.json          make coverage          core-logic coverage (EV-5)
  results/load_latency.json      make load-latency      PF-1
  results/load_concurrent.json   make load-concurrent   PF-2, PF-3
  results/eval/{golden,adversarial}.json   make eval-golden / eval-adversarial with OPENROUTER_API_KEY set

The evaluation tables come ONLY from results/eval/ (the real model). results/eval_stub/ is never read: the stub is not
a language model (docs/STUBS.md, S40). Where results/eval/ is missing the file says so plainly; a results/eval/ file
that claims to be a stub run is refused. Replies and issued values are never in these inputs, so none can be here.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from qrypt_entropy.agent.chat import FREE_TIER_LIMIT  # noqa: E402
from qrypt_entropy.agent.settings import AgentSettings  # noqa: E402

COMPOSE_DB = "the Docker Compose Postgres (docker-compose.yml, Postgres 18)"
NOT_RUN = (
    "**NOT RUN with the real model.** results/eval/ holds no real-model result for this set, so there are no figures "
    "to show. Run `make eval-golden` and `make eval-adversarial` with OPENROUTER_API_KEY set (docs/DEPLOY.md, "
    "section S40), then `make results`. Figures from the local stub are deliberately not shown."
)


def load(path: Path, make: str) -> dict:
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        sys.exit(f"missing {path.relative_to(ROOT)}: run `{make}` first")


def real_eval(root: Path) -> dict[str, dict]:
    """The real-model documents found in results/eval/. A document that is not the real model is an error."""
    docs = {}
    for suite in ("golden", "adversarial"):
        path = root / "results" / "eval" / f"{suite}.json"
        if path.exists():
            doc = json.loads(path.read_text())
            if not doc.get("real_model"):
                sys.exit(f"{path.relative_to(root)} is not a real-model run; refusing to present it as one")
            docs[suite] = doc
    return docs


def table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(str(c).replace("|", "/") for c in row) + " |" for row in rows]


def verdict(case: dict) -> str:
    return "PASS" if case["pass"] else "FAIL"


def eval_section(title: str, header: list[str], docs: dict, suite: str, row) -> list[str]:
    doc = docs.get(suite)
    if doc is None:
        return [f"## {title}", "", NOT_RUN, "", *table(header, [["-"] * len(header)]), ""]
    out = [f"## {title}", "", f"Result: {doc['passes']} of {doc['total']} passed (date {doc['date']}).", ""]
    if suite == "golden":
        cap = doc["outbound_capture"]
        out += [
            f"Fabricated values: {doc['fabrication']}. Tool returns without an audit record: {doc['audit_missing']}. "
            f"Reply time p95: {doc['reply_p95_s']} s (max {doc['reply_max_s']} s). "
            f"Outbound capture: {cap['matches']} matches for {cap['values_searched']} values shown.",
            "",
        ]
    return out + table(header, [row(c) for c in doc["cases"]]) + [""]


def build(root: Path = ROOT) -> str:
    res = root / "results"
    cov = load(res / "coverage.json", "make coverage")
    lat = load(res / "load_latency.json", "make load-latency")
    con = load(res / "load_concurrent.json", "make load-concurrent")
    docs = real_eval(root)
    load_p = con["latency_under_load_ms"]
    injected = con["injected_invalid_calls"]

    out = ["# Test results", "", "Generated by `make results` from the files in results/. Do not edit by hand.", ""]
    out += ["## Coverage", "", f"Threshold {cov['threshold_percent']:g}% on core logic (EV-5); CI fails below it.", ""]
    out += table(
        ["core area", "files", "coverage"],
        [[a, ", ".join(r["files"]), f"{r['percent']}%"] for a, r in cov["areas"].items()],
    )
    out += ["", f"All core logic: {cov['core_total_percent']}%. Whole package: {cov['suite_total_percent']}%.", ""]

    out += [
        "## Throughput and error rate",
        "",
        f"Throughput: {con['throughput_calls_per_s']} calls/s "
        f"({con['callers']} concurrent callers, {con['seconds']} s, {con['calls']} calls).",
        "",
        f"Error rate: {con['server_error_rate'] * 100:g}% server errors ({json.dumps(con['server_errors_by_code'])}). "
        f"Separately, {injected['sent']} of {con['calls']} calls ({round(100 * injected['sent'] / con['calls'], 2)}%) "
        f"were injected invalid calls and {injected['answered_invalid_argument']} were refused as invalid_argument: "
        f"{con['note_errors']}.",
        "",
    ]

    warm = f"warm pool, {lat['calls']} calls one at a time (PF-1, limit p95 under {lat['threshold_p95_ms']:g} ms)"
    out += ["## Latency (p50, p95, p99)", ""]
    out += table(
        ["run", "p50 ms", "p95 ms", "p99 ms"],
        [
            [warm, lat["p50_ms"], lat["p95_ms"], lat["p99_ms"]],
            [f"{con['callers']} callers at once (PF-2)", load_p["p50"], load_p["p95"], load_p["p99"]],
        ],
    )
    out += ["", f"Warm-pool errors: {lat['errors']}.", ""]

    out += [
        "## KiB per upstream request",
        "",
        f"Fetched per upstream request: {con['kib_fetched_per_upstream_request']} KiB "
        f"(startup check excluded, {con['upstream_requests_excluding_startup_check']} requests). "
        f"Served per upstream request: {con['kib_served_per_upstream_request']} KiB. "
        f"Most upstream requests in any 10 s: {con['max_upstream_requests_in_10s']}; 429s: {con['upstream_429s']}.",
        "",
    ]

    out += eval_section(
        "Golden set (EV-1)",
        ["id", "prompt", "expected tool", "result", "why not"],
        docs,
        "golden",
        lambda c: [c["id"], c["prompt"], c["tool"], verdict(c), c["reason"] or "-"],
    )
    out += eval_section(
        "Adversarial set (EV-3)",
        ["id", "attack", "prompt", "refused", "why not"],
        docs,
        "adversarial",
        lambda c: [c["id"], c["attack"], c["prompt"], verdict(c), c["reason"] or "-"],
    )

    env = lat["environment"]
    out += ["## Database, model and request count", ""]
    out += [
        f"Database: {COMPOSE_DB} is the documented database for the PF-1 run. The load runs in this file used: "
        f"{lat['database_used']}.",
        "",
        f"Upstream: {env['upstream']}.",
        "",
        f"Machine: {env['machine']}; Python {env['python']}.",
        "",
    ]
    if docs:
        first = next(iter(docs.values()))
        per_suite = ", ".join(f"{s} {d['model_requests']}" for s, d in docs.items())
        out += [
            f"Model: {first['model']} (real model, through OpenRouter).",
            "",
            f"Model limit: {first['free_tier_limit']}.",
            "",
            f"Model requests used: {sum(d['model_requests'] for d in docs.values())} ({per_suite}).",
        ]
    else:
        out += [
            f"Model: none run yet; the configured model is {AgentSettings.model_fields['agent_model'].default}.",
            "",
            f"Model limit: {FREE_TIER_LIMIT}.",
            "",
            "Model requests used: 0 (no real-model evaluation has run).",
        ]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "results" / "RESULTS.md"))
    args = parser.parse_args()
    text = build()
    Path(args.out).write_text(text)
    print(f"wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
